# frozen_string_literal: true

require "json"
require "yaml"

module DhanHQ
  module Contract
    # Emits generated artifacts from the vendored contract:
    #
    # * +lib/DhanHQ/contract/metadata.rb+ — frozen schema metadata for every
    #   component schema (properties, types, required lists), consumed by the
    #   contract specs and available to the model layer.
    # * +lib/DhanHQ/contract/params.rb+ — one self-validating request-param
    #   struct per request-body schema (+Params::Base+ subclasses).
    # * +docs/ENDPOINTS.md+ — the endpoint catalogue generated from the
    #   registry (rate-limit class, sandbox availability, docs-only markers).
    # * +docs/ws_lifecycle.asyncapi.yml+ — the AsyncAPI lifecycle document for
    #   the WebSocket feed, generated from contracts/dhanhq/ws_protocol.yml.
    #
    # Regenerate with +rake contract:generate+ (all artifacts),
    # +rake contract:docs+ (endpoint doc) or +rake contract:asyncapi+ (WS
    # lifecycle doc). The vendor contract is the input; nothing in the output
    # is hand-maintained.
    class Generator
      METADATA_PATH = File.expand_path("metadata.rb", __dir__)
      PARAMS_PATH = File.expand_path("params.rb", __dir__)
      ENDPOINTS_DOC_PATH = File.expand_path("../../../docs/ENDPOINTS.md", __dir__)
      ASYNCAPI_PATH = File.expand_path("../../../docs/ws_lifecycle.asyncapi.yml", __dir__)

      class << self
        def write_all!
          write_metadata!
          write_params!
          write_endpoints_doc!
          write_asyncapi!
        end

        def write_metadata!
          File.write(METADATA_PATH, metadata_source)
        end

        def write_params!
          File.write(PARAMS_PATH, params_source)
        end

        def write_endpoints_doc!
          File.write(ENDPOINTS_DOC_PATH, endpoints_doc)
        end

        def write_asyncapi!
          File.write(ASYNCAPI_PATH, asyncapi_source)
        end

        private

        # -- metadata.rb ----------------------------------------------------

        def metadata_source
          <<~RUBY
            # frozen_string_literal: true

            # GENERATED by `rake contract:generate` from contracts/dhanhq/*.openapi.json
            # (+ overlays). DO NOT EDIT BY HAND — rerun the rake task instead.
            #
            # Schema metadata for every component schema in the vendored live
            # document. Types are JSON Schema type names.

            module DhanHQ
              module Contract
                module Metadata
                  SCHEMAS = #{pretty_schemas}
                end
              end
            end
          RUBY
        end

        def pretty_schemas
          schemas = {}
          Registry.live_schemas.each do |name, schema|
            props = schema["properties"] || {}
            schemas[name] = {
              "type" => schema["type"],
              "required" => schema["required"] || [],
              "properties" => props.each_with_object({}) do |(key, spec), out|
                out[key] = {
                  "type" => Array(spec["type"]).join("|"),
                  "enum" => spec["enum"],
                  "description" => first_line(spec["description"])
                }.compact
              end
            }
          end
          ruby_literal(schemas, 0)
        end

        # Emits a Ruby hash/array literal with STRING keys. (Embedding
        # JSON.pretty_generate here would parse `"key":` as Ruby hash
        # shorthand and silently produce Symbol keys.)
        def ruby_literal(obj, indent)
          pad = "  " * indent
          inner_pad = "  " * (indent + 1)
          case obj
          when Hash
            return "{}" if obj.empty?

            rows = obj.map do |key, value|
              "#{inner_pad}#{key.inspect} => #{ruby_literal(value, indent + 1)}"
            end
            "{\n#{rows.join(",\n")}\n#{pad}}"
          when Array
            return "[]" if obj.empty?

            rows = obj.map { |value| "#{inner_pad}#{ruby_literal(value, indent + 1)}" }
            "[\n#{rows.join(",\n")}\n#{pad}]"
          else
            obj.inspect
          end
        end

        def first_line(text)
          return nil if text.nil?

          line = text.to_s.lines.first.to_s.strip[0, 160]
          line.empty? ? nil : line
        end

        # -- lib/DhanHQ/contract/params.rb -----------------------------------

        # One struct class per request-body schema. The wire key is the OpenAPI
        # property name; the struct field is its underscored form. Collisions
        # (two properties collapsing to one field name, or two schemas
        # collapsing to one class name) are generation failures, never silent.
        def params_source
          classes = request_schemas.map { |schema, ops| params_class_source(schema, ops) }
          op_map = operation_params_map
          # Composed line-by-line rather than via a squiggly heredoc: a
          # multi-line interpolation inside an indented heredoc prefixes the
          # FIRST inserted line with the interpolation's column position,
          # which would misindent every class comment.
          [
            "# frozen_string_literal: true",
            "",
            "# GENERATED by `rake contract:generate` from contracts/dhanhq/*.openapi.json",
            "# (+ overlays). DO NOT EDIT BY HAND — rerun the rake task instead.",
            "#",
            "# One self-validating request-param struct per request-body schema",
            "# in the vendored live document (base class: Params::Base). Fields",
            "# mirror the schema properties; required lists omit the fields the",
            "# client injects (Params::Base::INJECTED_FIELDS).",
            "",
            "module DhanHQ",
            "  module Contract",
            "    module Params",
            "      # operationId => param struct class name",
            "      OPERATION_PARAMS = #{ruby_literal(op_map, 3)}",
            "",
            classes.join("\n\n"),
            "    end",
            "  end",
            "end",
            ""
          ].join("\n")
        end

        # @return [Hash{String => String}] operationId => class name
        def operation_params_map
          request_schemas.each_with_object({}) do |(schema_name, ops), out|
            ops.each { |op| out[op.id] = params_class_name(schema_name) }
          end.sort.to_h
        end

        # @return [Array<Array(String, Array<Operation>)>] schema name +
        #   the operations carrying it, ordered by schema name
        def request_schemas
          by_schema = Hash.new { |h, k| h[k] = [] }
          Registry.operations.each_value do |op|
            next unless op.request_schema_name

            by_schema[op.request_schema_name] << op
          end
          by_schema.sort
        end

        def params_class_name(schema_name)
          base = schema_name.sub(/\A(.+?)(Request|Req|Model)\z/, '\1')
          name = "#{base}Params"
          taken = @params_class_names ||= {}
          if (existing = taken[name]) && existing != schema_name
            raise "params class name collision: #{schema_name} and #{existing} both map to #{name}"
          end

          taken[name] = schema_name
          name
        end

        def params_class_source(schema_name, operations)
          schema = Registry.live_schemas[schema_name]
          raise "request schema #{schema_name} missing from the live contract" unless schema

          fields = params_fields(schema_name, schema)
          class_name = params_class_name(schema_name)
          usage = operations.map { |op| "#{op.verb.to_s.upcase} #{op.path} (#{op.id})" }.join(", ")
          header = "# #{usage} — request body schema `#{schema_name}`"
          body = <<~RUBY
            #{header}
            class #{class_name} < Base
              SCHEMA_NAME = #{schema_name.inspect}
              OPERATION_IDS = #{ruby_literal(operations.map(&:id).sort, 1)}.freeze
              FIELDS = #{ruby_literal(fields, 1)}.freeze
              REQUIRED = #{ruby_literal(fields.select { |_n, s| s["required"] }.keys.sort, 1)}.freeze
            end
          RUBY
          body.lines.map { |line| line == "\n" ? line : "      #{line}" }.join
        end

        def params_fields(schema_name, schema)
          required = (schema["required"] || []) - Params::Base::INJECTED_FIELDS
          props = schema["properties"] || {}
          seen = {}
          props.each_with_object({}) do |(wire_key, spec), out|
            field = wire_key.underscore
            raise "params field collision in #{schema_name}: #{wire_key} and #{seen[field]} both map to #{field}" if seen.key?(field)

            seen[field] = wire_key
            entry = { "wire_key" => wire_key, "required" => required.include?(wire_key) }
            type = Array(spec["type"]).join("|")
            entry["type"] = type unless type.empty?
            entry["enum"] = spec["enum"].dup.freeze if spec["enum"].is_a?(Array) && !spec["enum"].empty?
            out[field] = entry
          end
        end

        # -- docs/ENDPOINTS.md ----------------------------------------------

        def endpoints_doc
          by_tag = Hash.new { |h, k| h[k] = [] }
          Registry.operations.each_value do |op|
            by_tag[tag_for(op)] << op
          end

          rows = <<~MD
            # DhanHQ v2 Endpoint Catalogue

            <!-- GENERATED by `rake contract:docs` from the vendored OpenAPI
                 documents (contracts/dhanhq/) and their overlays. Do not edit
                 by hand — the authoritative surface is the contract. -->

            #{Registry.operations.size} operations: #{Registry.live_operation_ids.size} from the
            vendor document, #{Registry.operations.values.count(&:docs_only?)} docs-only via
            overlay 0001. Sandbox column = served by sandbox.dhan.co/v2 (see
            overlays 0003/0004).

          MD

          %w[Orders Super Order Conditional and Multi Order Forever Order
             Positions & Portfolio EDIS Trader's Control Funds & Margin
             Statements Data API's Docs-only IP Setup Global Stocks].each do |tag|
            ops = by_tag[tag]
            next if ops.nil? || ops.empty?

            rows << "\n## #{tag}\n\n"
            rows << "| Endpoint | Tier | Param keys | Sandbox | Notes |\n"
            rows << "|---|---|---|---|---|\n"
            ops.sort_by(&:id).each do |op|
              notes = []
              notes << "docs-only" if op.docs_only?
              notes << op.summary.to_s.sub(/\s*\(docs-only\)\s*/, "") if op.summary
              rows << "| `#{op.verb.to_s.upcase} #{op.path}` (`#{op.id}`) | #{op.rate_limit_class} | " \
                      "#{op.param_style} | #{op.sandbox_supported? ? "yes" : "—"} | #{notes.join(" — ")} |\n"
            end
          end

          leftovers = by_tag.keys - %w[Orders Super Order Conditional and Multi Order
                                       Forever Order Positions & Portfolio EDIS
                                       Trader's Control Funds & Margin Statements
                                       Data API's Docs-only IP Setup Global Stocks]
          leftovers.sort.each do |tag|
            ops = by_tag[tag]
            rows << "\n## #{tag}\n\n"
            rows << "| Endpoint | Tier | Param keys | Sandbox | Notes |\n"
            rows << "|---|---|---|---|---|\n"
            ops.sort_by(&:id).each do |op|
              rows << "| `#{op.verb.to_s.upcase} #{op.path}` (`#{op.id}`) | #{op.rate_limit_class} | " \
                      "#{op.param_style} | #{op.sandbox_supported? ? "yes" : "—"} | #{op.summary} |\n"
            end
          end

          rows
        end

        def tag_for(operation)
          path_item = Registry.live_doc.dig("paths", operation.path) || {}
          item = path_item[operation.verb.to_s] || {}
          item["tags"]&.first || "Docs-only"
        end

        # -- docs/ws_lifecycle.asyncapi.yml ----------------------------------

        # The AsyncAPI 2.6 lifecycle document for the WebSocket feed,
        # generated from contracts/dhanhq/ws_protocol.yml (the machine-readable
        # byte-level manifest). Nothing here is hand-maintained: servers,
        # channels, messages, payloads and the lifecycle extension all derive
        # from the manifest, and spec/dhan_hq/ws/asyncapi_spec.rb locks the
        # committed artifact to a fresh regeneration byte-for-byte.
        def asyncapi_source
          YAML.dump(asyncapi_document)
        end

        def asyncapi_document
          manifest = WS::Protocol.manifest
          {
            "asyncapi" => "2.6.0",
            "info" => {
              "title" => "DhanHQ Live Market Feed — lifecycle contract",
              "version" => manifest.dig("meta", "version").to_s,
              "description" => asyncapi_description
            },
            "servers" => asyncapi_servers(manifest),
            "channels" => asyncapi_channels(manifest),
            "components" => { "messages" => asyncapi_messages(manifest) },
            "x-dhan-lifecycle" => asyncapi_lifecycle(manifest)
          }
        end

        def twenty_depth_description(manifest)
          limits = manifest.dig("full_market_depth", "limits")
          "20-level full market depth socket " \
            "(max #{limits.fetch("twenty_level_instruments")} instruments, " \
            "segments #{limits.fetch("segments").join("/")})."
        end

        def asyncapi_description
          <<~TEXT.chomp
            GENERATED by `rake contract:asyncapi` from contracts/dhanhq/ws_protocol.yml.
            Do not edit by hand — regenerate instead.

            Describes the DhanHQ v2 live market feed: how a client connects and
            authenticates, the JSON command frames it publishes (subscribe /
            unsubscribe / disconnect), and the binary packet frames it receives
            in return. Byte layouts are carried in the x-dhan-struct extension
            of each message payload, copied verbatim from the ws_protocol.yml
            manifest; heartbeat, connection limits and disconnect codes live
            under x-dhan-lifecycle. Every field is LITTLE-ENDIAN; prices are
            IEEE-754 rupees (no multipliers); epochs are seconds.
          TEXT
        end

        def asyncapi_servers(manifest)
          conn = manifest.fetch("connection")
          depth = conn.fetch("market_depth_urls")
          ws_binding = lambda { |query|
            { "ws" => { "query" => query, "bindingVersion" => "0.1.0" } }
          }
          {
            "market_feed" => {
              "url" => conn.fetch("v2_url"),
              "protocol" => "wss",
              "description" => "v2 live market feed. Query params are mandatory: version=2, token (access token), clientId, authType=2. No Authorization header.",
              "bindings" => ws_binding.call(
                { "version" => 2, "token" => "{token}", "clientId" => "{clientId}", "authType" => 2 }
              )
            },
            "twenty_depth" => {
              "url" => depth.fetch("twenty_level"),
              "protocol" => "wss",
              "description" => twenty_depth_description(manifest)
            },
            "two_hundred_depth" => {
              "url" => depth.fetch("twohundred_level"),
              "protocol" => "wss",
              "description" => "200-level full market depth socket (max #{manifest.dig("full_market_depth", "limits", "twohundred_level_instruments")} instrument)."
            }
          }
        end

        def asyncapi_channels(manifest)
          feed_ops = {
            "publish" => {
              "operationId" => "sendFeedCommand",
              "description" => "JSON command frames the client publishes: per-family subscribe/unsubscribe and the whole-connection disconnect.",
              "message" => { "oneOf" => request_message_refs(manifest) + [{ "$ref" => "#/components/messages/disconnectFeed" }] }
            },
            "subscribe" => {
              "operationId" => "receiveFeedPackets",
              "description" => "Binary packet frames pushed by the server. Split stacked frames by the 8-byte header's message_length.",
              "message" => { "oneOf" => packet_message_refs(manifest) }
            }
          }
          depth_ops = {
            "publish" => {
              "operationId" => "sendDepthCommand",
              "description" => "Subscribe/unsubscribe instruments on a full-market-depth socket (request codes from request_codes.market_depth).",
              "message" => { "oneOf" => %w[subscribe unsubscribe].map { |dir| depth_message_ref(dir) } }
            },
            "subscribe" => {
              "operationId" => "receiveFullMarketDepth",
              "description" => "Stacked FMD frames: a 12-byte header followed by rows of 16 bytes; frame sizes in x-dhan-struct.",
              "message" => { "$ref" => "#/components/messages/feedFullMarketDepth" }
            }
          }
          {
            "marketfeed" => feed_ops.merge("description" => "Live market feed (ticker / quote / index / depth / full / OI / prev-close / market status / disconnect)."),
            "twenty-depth" => depth_ops.merge("description" => "20-level full market depth."),
            "two-hundred-depth" => depth_ops.merge("description" => "200-level full market depth.")
          }
        end

        # -- messages ----------------------------------------------------------

        def request_message_refs(manifest)
          manifest.fetch("request_codes").fetch("subscribe").keys.map do |family|
            { "$ref" => "#/components/messages/subscribe#{pascal(family)}" }
          end + manifest.fetch("request_codes").fetch("unsubscribe").keys.map do |family|
            { "$ref" => "#/components/messages/unsubscribe#{pascal(family)}" }
          end
        end

        def packet_message_refs(manifest)
          manifest.fetch("packets").keys.map do |packet|
            { "$ref" => "#/components/messages/feed#{pascal(packet)}" }
          end
        end

        def depth_message_ref(direction)
          { "$ref" => "#/components/messages/#{direction}MarketDepth" }
        end

        def asyncapi_messages(manifest)
          msgs = {}
          request_codes = manifest.fetch("request_codes")
          %w[subscribe unsubscribe].each do |direction|
            request_codes.fetch(direction).each do |family, code|
              msgs["#{direction}#{pascal(family)}"] = request_message(code, family, direction, manifest)
            end
          end
          msgs["disconnectFeed"] = {
            "description" => "Whole-connection teardown frame (RequestCode 12). This is NOT an unsubscribe.",
            "payload" => {
              "type" => "object",
              "required" => ["requestCode"],
              "properties" => { "requestCode" => { "type" => "integer", "const" => manifest.fetch("request_codes").fetch("disconnect") } }
            }
          }
          manifest.fetch("packets").each do |packet, layout|
            msgs["feed#{pascal(packet)}"] = packet_message(packet, layout, manifest)
          end
          msgs["feedFullMarketDepth"] = {
            "description" => "Stacked full-market-depth frames (header + rows); sizes and limits in x-dhan-struct.",
            "payload" => {
              "type" => "object",
              "x-dhan-struct" => manifest.fetch("full_market_depth")
            }
          }
          msgs
        end

        def request_message_description(direction, family, code)
          "#{direction.to_s.capitalize} #{family} on the live feed. " \
            "RequestCode #{code} (unsubscribe = subscribe + 1, " \
            "except the index family: subscribe 14 / unsubscribe 13)."
        end

        def request_message(code, family, direction, manifest)
          payload_shape = manifest.fetch("request_payload")
          instrument = payload_shape.fetch("instrument")
          {
            "description" => request_message_description(direction, family, code),
            "payload" => {
              "type" => "object",
              "required" => [payload_shape.fetch("request_code_key"), payload_shape.fetch("instruments_key")],
              "properties" => {
                payload_shape.fetch("request_code_key") => { "type" => "integer", "const" => code },
                payload_shape.fetch("instruments_key") => {
                  "type" => "array",
                  "maxItems" => manifest.dig("connection", "max_instruments_per_json_message"),
                  "items" => {
                    "type" => "object",
                    "required" => instrument.fetch("required"),
                    "properties" => instrument.fetch("properties").each_with_object({}) do |(key, type), out|
                      out[key] = { "type" => type }
                    end
                  }
                }
              }
            }
          }
        end

        def packet_message(packet, layout, manifest)
          msg = {
            "description" => "Server frame, first byte = #{layout["code"]}, #{layout["size"]} bytes. Byte layout in x-dhan-struct (offsets 0-based; header occupies 0–7).",
            "payload" => {
              "type" => "object",
              "x-dhan-struct" => layout
            }
          }
          if packet == "disconnect"
            msg["examples"] = manifest.fetch("disconnect_codes").map do |code, reason|
              { "payload" => { "disconnection_code" => code.to_i }, "summary" => reason }
            end
          end
          msg
        end

        def asyncapi_lifecycle(manifest)
          manifest.fetch("connection").merge("disconnect_codes" => manifest.fetch("disconnect_codes"))
        end

        def pascal(snake)
          snake.to_s.split("_").map(&:capitalize).join
        end
      end
    end
  end
end
