# frozen_string_literal: true

require "json"

module DhanHQ
  module Contract
    # Emits generated artifacts from the vendored contract:
    #
    # * +lib/DhanHQ/contract/metadata.rb+ — frozen schema metadata for every
    #   component schema (properties, types, required lists), consumed by the
    #   contract specs and available to the model layer.
    # * +docs/ENDPOINTS.md+ — the endpoint catalogue generated from the
    #   registry (rate-limit class, sandbox availability, docs-only markers).
    #
    # Regenerate with +rake contract:generate+ (metadata + docs) or
    # +rake contract:docs+ (docs only). The vendor contract is the input;
    # nothing in the output is hand-maintained.
    class Generator
      METADATA_PATH = File.expand_path("metadata.rb", __dir__)
      ENDPOINTS_DOC_PATH = File.expand_path("../../../docs/ENDPOINTS.md", __dir__)

      class << self
        def write_all!
          write_metadata!
          write_endpoints_doc!
        end

        def write_metadata!
          File.write(METADATA_PATH, metadata_source)
        end

        def write_endpoints_doc!
          File.write(ENDPOINTS_DOC_PATH, endpoints_doc)
        end

        private

        # -- metadata.rb ----------------------------------------------------

        def metadata_source
          <<~RUBY
            # frozen_string_literal: true

            # GENERATED by `rake contract:generate` from contracts/dhanhq/*.openapi.json
            # (+ overlays). DO NOT EDIT BY HAND — rerun the rake task instead.
            #
            # Schema metadata for every component schema in the vendored live
            # document. Types are JSON Schema type names.

            module DhanHQ
              module Contract
                module Metadata
                  SCHEMAS = #{pretty_schemas}
                end
              end
            end
          RUBY
        end

        def pretty_schemas
          schemas = {}
          Registry.live_schemas.each do |name, schema|
            props = schema["properties"] || {}
            schemas[name] = {
              "type" => schema["type"],
              "required" => schema["required"] || [],
              "properties" => props.each_with_object({}) do |(key, spec), out|
                out[key] = {
                  "type" => Array(spec["type"]).join("|"),
                  "enum" => spec["enum"],
                  "description" => first_line(spec["description"])
                }.compact
              end
            }
          end
          ruby_literal(schemas, 0)
        end

        # Emits a Ruby hash/array literal with STRING keys. (Embedding
        # JSON.pretty_generate here would parse `"key":` as Ruby hash
        # shorthand and silently produce Symbol keys.)
        def ruby_literal(obj, indent)
          pad = "  " * indent
          inner_pad = "  " * (indent + 1)
          case obj
          when Hash
            return "{}" if obj.empty?

            rows = obj.map do |key, value|
              "#{inner_pad}#{key.inspect} => #{ruby_literal(value, indent + 1)}"
            end
            "{\n#{rows.join(",\n")}\n#{pad}}"
          when Array
            return "[]" if obj.empty?

            rows = obj.map { |value| "#{inner_pad}#{ruby_literal(value, indent + 1)}" }
            "[\n#{rows.join(",\n")}\n#{pad}]"
          else
            obj.inspect
          end
        end

        def first_line(text)
          return nil if text.nil?

          line = text.to_s.lines.first.to_s.strip[0, 160]
          line.empty? ? nil : line
        end

        # -- docs/ENDPOINTS.md ----------------------------------------------

        def endpoints_doc
          by_tag = Hash.new { |h, k| h[k] = [] }
          Registry.operations.each_value do |op|
            by_tag[tag_for(op)] << op
          end

          rows = +<<~MD
            # DhanHQ v2 Endpoint Catalogue

            <!-- GENERATED by `rake contract:docs` from the vendored OpenAPI
                 documents (contracts/dhanhq/) and their overlays. Do not edit
                 by hand — the authoritative surface is the contract. -->

            #{Registry.operations.size} operations: #{Registry.live_operation_ids.size} from the
            vendor document, #{Registry.operations.values.count(&:docs_only?)} docs-only via
            overlay 0001. Sandbox column = served by sandbox.dhan.co/v2 (see
            overlays 0003/0004).

            MD

          %w[Orders Super Order Conditional and Multi Order Forever Order
             Positions & Portfolio EDIS Trader's Control Funds & Margin
             Statements Data API's Docs-only IP Setup Global Stocks].each do |tag|
            ops = by_tag[tag]
            next if ops.nil? || ops.empty?

            rows << "\n## #{tag}\n\n"
            rows << "| Endpoint | Tier | Param keys | Sandbox | Notes |\n"
            rows << "|---|---|---|---|---|\n"
            ops.sort_by(&:id).each do |op|
              notes = []
              notes << "docs-only" if op.docs_only?
              notes << op.summary.to_s.sub(/\s*\(docs-only\)\s*/, "") if op.summary
              rows << "| `#{op.verb.to_s.upcase} #{op.path}` (`#{op.id}`) | #{op.rate_limit_class} | " \
                      "#{op.param_style} | #{op.sandbox_supported? ? "yes" : "—"} | #{notes.join(" — ")} |\n"
            end
          end

          leftovers = by_tag.keys - %w[Orders Super Order Conditional and Multi Order
                                       Forever Order Positions & Portfolio EDIS
                                       Trader's Control Funds & Margin Statements
                                       Data API's Docs-only IP Setup Global Stocks]
          leftovers.sort.each do |tag|
            ops = by_tag[tag]
            rows << "\n## #{tag}\n\n"
            rows << "| Endpoint | Tier | Param keys | Sandbox | Notes |\n"
            rows << "|---|---|---|---|---|\n"
            ops.sort_by(&:id).each do |op|
              rows << "| `#{op.verb.to_s.upcase} #{op.path}` (`#{op.id}`) | #{op.rate_limit_class} | " \
                      "#{op.param_style} | #{op.sandbox_supported? ? "yes" : "—"} | #{op.summary} |\n"
            end
          end

          rows
        end

        def tag_for(op)
          path_item = Registry.live_doc.dig("paths", op.path) || {}
          item = path_item[op.verb.to_s] || {}
          item["tags"]&.first || "Docs-only"
        end
      end
    end
  end
end
